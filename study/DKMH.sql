SELECT TENMH, DKMH.MAMH, NHOM, THU, TIETBD, SOTIET, PHONG, GVIEN
FROM DKMH JOIN MONHOC ON DKMH.MAMH = MONHOC.MAMH
WHERE
((DKMH.MAMH LIKE '861305')
AND
(NHOM = '03' OR NHOM = '04'))
OR
((DKMH.MAMH LIKE '861304')
AND
(NHOM = '07' OR NHOM = '06'))
OR
((DKMH.MAMH LIKE 'BORO11')
AND
(NHOM = '02' OR NHOM = '05'))

